alter table pos_invoices add column if not exists icv bigint;
alter table pos_invoices add column if not exists previous_invoice_hash text;
alter table pos_invoices add column if not exists invoice_hash text;
alter table pos_invoices add column if not exists cryptographic_stamp text;
alter table pos_invoices add column if not exists zatca_status text;
