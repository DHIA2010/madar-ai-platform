-- WhatsApp Business Platform (Meta's Cloud API, no third-party provider): Madar's own app and
-- account, set up from Madar Admin -> settings -> WhatsApp. One row. The app secret and the
-- System User token are stored encrypted and never sent back to the browser.
create table if not exists whatsapp_platform_config (
  id integer primary key default 1 check (id = 1),
  app_id text not null default '',
  embedded_signup_config_id text not null default '',
  madar_waba_id text not null default '',
  madar_phone_number_id text not null default '',
  app_secret_encrypted text,
  system_user_token_encrypted text,
  -- Meta sends it back when verifying the webhook URL; generated by Madar.
  webhook_verify_token text not null default '',
  updated_at timestamptz not null default now(),
  updated_by uuid references users(id) on delete set null
);

-- Every event Meta posts to the webhook (message statuses, incoming messages, template reviews),
-- kept as received; processed into delivery statuses by the features that send messages.
create table if not exists whatsapp_webhook_events (
  id uuid primary key,
  received_at timestamptz not null default now(),
  payload jsonb not null
);
create index if not exists idx_whatsapp_webhook_events_received on whatsapp_webhook_events(received_at desc);
